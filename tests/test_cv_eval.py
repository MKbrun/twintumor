"""Tests for leave-one-patient-out CV."""

import pandas as pd

from src.data.loaders import load_demo_dataset
from src.models.cv_eval import leave_one_patient_out


def test_lopo_runs_on_small_subset():
    df = load_demo_dataset().head(8).copy()  # 8 patients × 2 scenarios = 16 rows
    summary, per_patient = leave_one_patient_out(df)
    assert not summary.empty
    assert not per_patient.empty
    assert set(per_patient["subject"].unique()) == set(df["subject"].unique())
    # 2 rows per held-out patient (progression + remission)
    assert len(per_patient) == len(df) * 2


def test_lopo_summary_has_every_model_and_timepoint():
    df = load_demo_dataset().head(6).copy()
    summary, _ = leave_one_patient_out(df)
    expected_models = {
        "Exponential", "Gompertz",
        "Linear Regression", "Random Forest (depth=6)",
        "Gradient Boosting", "MLP (64,32)",
    }
    assert expected_models.issubset(set(summary["Model"]))
    assert {"FU3", "FU4", "FU5", "FU3-FU5 mean"} == set(summary["Timepoint"])


def test_lopo_progress_callback_invoked():
    df = load_demo_dataset().head(4).copy()
    seen = []
    def cb(i, total, pid):
        seen.append((i, total, pid))
    leave_one_patient_out(df, progress=cb)
    assert len(seen) == 4
    assert seen[0][1] == 4
    assert seen[-1][0] == 4


def test_lopo_empty_input():
    s, p = leave_one_patient_out(pd.DataFrame())
    assert s.empty and p.empty


def test_lopo_no_subject_appears_in_both_train_and_test():
    """Patient-level partitioning property: a subject's predictions in
    `per_patient` were generated by a model that did not see that subject."""
    df = load_demo_dataset().head(5).copy()
    _, per_patient = leave_one_patient_out(df)
    # Every subject should appear in per_patient as the held-out one,
    # exactly twice (progression + remission).
    counts = per_patient["subject"].value_counts()
    assert (counts == 2).all()
